package handlers

import (
	"bytes"
	"regexp"
	"strings"

	"github.com/computerguymackay/metakill/report"
)

// Manifest attributes that identify who built a JAR, on which machine, with
// which tools, and when. Header names are case-insensitive.
var manifestDrop = map[string]report.Category{
	"built-by":              report.CatAuthor,
	"created-by":            report.CatSoftware,
	"originally-created-by": report.CatSoftware,
	"build-jdk":             report.CatSoftware,
	"build-jdk-spec":        report.CatSoftware,
	"ant-version":           report.CatSoftware,
	"archiver-version":      report.CatSoftware,
	"tool":                  report.CatSoftware,
	"build-os":              report.CatDevice,
	"build-host":            report.CatDevice,
	"built-host":            report.CatDevice,
	"built-on":              report.CatDevice,
	"bnd-lastmodified":      report.CatTimestamp,
}

var manifestTime = regexp.MustCompile(`(?i)^(build|built)-.*(date|time|timestamp)$`)

// splitLines splits b into lines, each keeping its line ending.
func splitLines(b []byte) [][]byte {
	var out [][]byte
	for len(b) > 0 {
		i := bytes.IndexByte(b, '\n')
		if i < 0 {
			out = append(out, b)
			break
		}
		out = append(out, b[:i+1])
		b = b[i+1:]
	}
	return out
}

func trimEOL(b []byte) []byte { return bytes.TrimRight(b, "\r\n") }

// cleanManifest removes identifying attributes from a JAR manifest, keeping
// every other byte (line endings, 72-byte wrapping, section order) as it was.
func cleanManifest(b []byte) ([]byte, []report.Field) {
	lines := splitLines(b)
	var out []byte
	var fields []report.Field
	for i := 0; i < len(lines); {
		// A logical attribute is one line plus continuation lines (" ...").
		j := i + 1
		for j < len(lines) && len(lines[j]) > 0 && lines[j][0] == ' ' {
			j++
		}
		first := trimEOL(lines[i])
		key, val, ok := bytes.Cut(first, []byte(":"))
		name := strings.ToLower(strings.TrimSpace(string(key)))
		cat, drop := manifestDrop[name]
		if !drop && ok && manifestTime.MatchString(name) {
			cat, drop = report.CatTimestamp, true
		}
		if ok && drop {
			v := strings.TrimPrefix(string(val), " ")
			for _, c := range lines[i+1 : j] {
				v += string(trimEOL(c)[1:])
			}
			fields = append(fields, report.Text(cat, "jar.manifest", strings.TrimSpace(string(key)), v))
		} else {
			for _, l := range lines[i:j] {
				out = append(out, l...)
			}
		}
		i = j
	}
	return out, fields
}

// cleanPomProperties removes the comment lines Maven writes into
// pom.properties ("#Generated by Maven" and the build timestamp).
func cleanPomProperties(b []byte) ([]byte, []report.Field) {
	var out []byte
	var fields []report.Field
	for _, l := range splitLines(b) {
		t := strings.TrimSpace(string(trimEOL(l)))
		if strings.HasPrefix(t, "#") || strings.HasPrefix(t, "!") {
			c := strings.TrimSpace(t[1:])
			cat := report.CatCustom
			switch {
			case strings.HasPrefix(strings.ToLower(c), "generated by"), strings.HasPrefix(strings.ToLower(c), "created by"):
				cat = report.CatSoftware
			case looksLikeDate(c):
				cat = report.CatTimestamp
			}
			fields = append(fields, report.Text(cat, "jar.pom", "comment", c))
			continue
		}
		out = append(out, l...)
	}
	return out, fields
}

var dateLike = regexp.MustCompile(`\b(19|20)\d\d\b`)

func looksLikeDate(s string) bool { return dateLike.MatchString(s) && strings.ContainsAny(s, ":") }

// cleanJarMetadata cleans the manifest and Maven properties of an unsigned
// JAR. Signed JARs never get here: they are skipped as special packages.
func (z *zipDoc) cleanJarMetadata(e *zipEntry) bool {
	var clean func([]byte) ([]byte, []report.Field)
	switch {
	case strings.EqualFold(e.name, "META-INF/MANIFEST.MF"):
		clean = cleanManifest
	case strings.HasPrefix(e.name, "META-INF/maven/") && strings.HasSuffix(e.name, "/pom.properties"):
		clean = cleanPomProperties
	default:
		return false
	}
	out, fields := clean(e.data)
	if len(fields) > 0 {
		z.rep.Add(fields...)
		e.out = out
	}
	return true
}
